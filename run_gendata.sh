#!/bin/bash

# ==========================================
# Script Δημιουργίας Δεδομένων
# ==========================================

SAMPLES=${1:-10000000}
FEATURES=${2:-128}
OUTPUT=${3:-data_10M_128.bin}

echo "================================================="
echo " Ξεκινάει η δημιουργία δεδομένων..."
echo " Αρχείο: $OUTPUT | Γραμμές: $SAMPLES | Στήλες: $FEATURES"
echo "================================================="

python3 generate_data.py \
  --samples $SAMPLES \
  --features $FEATURES \
  --output $OUTPUT \
  --dtype float64

echo " Η δημιουργία ολοκληρώθηκε!"